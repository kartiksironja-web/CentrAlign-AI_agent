"""Aggregating evaluation records into evals/RESULTS.md.

Purpose: count the per-run records and render the results document.
Why this design: RESULTS.md is generated by code from stored records (evals/results/<batch>.json)
and is never edited by hand, so every number in it can be re-derived: `python -m evals.run_evals
--results-from evals/results/<batch>.json` regenerates it. Rates always show the counts they
come from (2/3), and runs that could not be completed (budget skipped, harness errors) are
listed, not dropped from view. Nothing here is interpreted: no "the agent is reliable".
How it can fail: with 3 runs per scenario a rate moves by 33 points per run; the document says
so. Averages over runs with an unknown model price say "unknown" instead of guessing.
"""
HEADER = """\
# Evaluation results

> Generated by `python -m evals.run_evals` from stored run records. **Do not edit by hand.**
> Metric definitions: [evals/README.md](README.md). Scenario definitions: [scenarios.yaml](scenarios.yaml).
"""


def ratio(n: int, d: int) -> str:
    return f"{n}/{d} ({round(100 * n / d)}%)" if d else "n/a"


def mean(values: list[float | int | None], digits: int = 1) -> str:
    known = [v for v in values if v is not None]
    if not known or len(known) != len(values):
        return "unknown" if values else "n/a"
    return f"{sum(known) / len(known):.{digits}f}"


def money(values: list[float | None], per: str) -> str:
    known = [v for v in values if v is not None]
    if not values:
        return "n/a"
    if len(known) != len(values):
        return "unknown"
    return f"${sum(known) / len(known):.3f}" if per == "avg" else f"${sum(known):.2f}"


def counted(records: list[dict]) -> list[dict]:
    return [r for r in records if r["outcome"] != "skipped_budget"]


def summary_table(scenarios: list[str], records: list[dict]) -> list[str]:
    lines = ["| Scenario | Runs | Meets expectations | Auditor-verified success | Ground truth OK | First claim correct | "
             "False completion | Self-caught repair | Auditor-caught repair | Auditor false pass |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for sid in scenarios:
        rs = [r for r in counted(records) if r["scenario"] == sid]
        claims = [r for r in rs if r["first_claim_made"]]
        lines.append(" | ".join(["", sid, str(len(rs)),
                                 ratio(sum(r["meets_expectations"] for r in rs), len(rs)),
                                 ratio(sum(r["verified_success"] for r in rs), len(rs)),
                                 ratio(sum(r["ground_truth_ok"] for r in rs), len(rs)),
                                 ratio(sum(bool(r["first_claim_correct"]) for r in claims), len(claims)),
                                 ratio(sum(r["false_completion"] for r in claims), len(claims)),
                                 ratio(sum(r["self_caught"] for r in rs), len(rs)),
                                 ratio(sum(r["auditor_caught"] for r in rs), len(rs)),
                                 ratio(sum(r["auditor_false_pass"] for r in rs), len(rs)), ""]).strip())
    return lines


def effort_table(scenarios: list[str], records: list[dict]) -> list[str]:
    lines = ["| Scenario | Avg steps | Avg retries | Avg human interactions | Avg gate blocks | Avg tokens in / out | "
             "Avg cost at list price | Avg wall time (s) |", "|---|---|---|---|---|---|---|---|"]
    for sid in scenarios:
        rs = [r for r in counted(records) if r["scenario"] == sid]
        lines.append("| " + " | ".join([
            sid, mean([r["steps"] for r in rs]), mean([r["retries"] for r in rs]), mean([r["humans"] for r in rs]),
            mean([r["gate_blocks"] for r in rs]),
            f"{mean([r['tokens_in'] for r in rs], 0)} / {mean([r['tokens_out'] for r in rs], 0)}",
            money([r["cost_usd"] for r in rs], "avg"), mean([r["wall_seconds"] for r in rs], 0)]) + " |")
    return lines


def detector_table(scenarios: list[str], records: list[dict]) -> list[str]:
    classes = sorted({k for r in records for k in r["detectors"]})
    if not classes:
        return ["No detector fired."]
    lines = ["| Scenario | " + " | ".join(classes) + " |", "|---|" + "---|" * len(classes)]
    for sid in scenarios:
        rs = [r for r in counted(records) if r["scenario"] == sid]
        lines.append(f"| {sid} | " + " | ".join(str(sum(r["detectors"].get(c, 0) for r in rs)) for c in classes) + " |")
    return lines


def mode_comparison(records: list[dict]) -> list[str]:
    pairs = [(a, b) for a, b in (("S3", "S3-advisory"),) if any(r["scenario"] == a for r in records)
             and any(r["scenario"] == b for r in records)]
    if not pairs:
        return ["The enforce/advisory pair (S3, S3-advisory) was not part of this batch."]
    lines = ["| Audit mode | Runs | First claim wrong | Wrong result left standing (ground truth) | Auditor-verified success |",
             "|---|---|---|---|---|"]
    for sid, label in (("S3", "enforce (audit result fed back, repairs allowed)"),
                       ("S3-advisory", "advisory (audit recorded only; the first claim is final)")):
        rs = [r for r in counted(records) if r["scenario"] == sid]
        claims = [r for r in rs if r["first_claim_made"]]
        lines.append(f"| {label} | {len(rs)} | {ratio(sum(r['false_completion'] for r in claims), len(claims))} | "
                     f"{ratio(sum(not r['ground_truth_ok'] for r in rs), len(rs))} | "
                     f"{ratio(sum(r['verified_success'] for r in rs), len(rs))} |")
    return lines


def run_list(records: list[dict]) -> list[str]:
    lines = ["| Scenario | # | Run id | Outcome | Steps | Ground truth | Meets expectations | Unmet |", "|---|---|---|---|---|---|---|---|"]
    for r in records:
        lines.append(f"| {r['scenario']} | {r['repeat']} | {r['run_id'] or '-'} | {r['outcome']} | {r['steps']} | "
                     f"{'ok' if r['ground_truth_ok'] else 'WRONG'} | {'yes' if r['meets_expectations'] else 'NO'} | "
                     f"{'; '.join(r['unmet']) or '-'} |")
    return lines


def render_results(batch: dict, records: list[dict]) -> str:
    real = counted(records)
    skipped = [r for r in records if r["outcome"] == "skipped_budget"]
    errors = [r for r in real if r["outcome"] in ("harness_error", "error")]
    out = [HEADER, "## Provenance", "",
           f"- batch: `{batch['batch_id']}`, started {batch['started_at']}, finished {batch['finished_at']}",
           f"- model: `{batch['model']}`, temperature: {batch['temperature'] if batch['temperature'] is not None else 'not sent'}",
           f"- repeats per scenario: {batch['repeats']}; scenarios: {', '.join(batch['scenarios'])}",
           f"- command: `{batch['command']}`",
           f"- run limits: {batch['limits']}",
           f"- human answers: SCRIPTED_HUMAN (pre-written, not a real person); the faults are test conditions injected on purpose"]
    if batch["model"].startswith("fake"):
        out.append("- **WARNING: this batch used a scripted fake model, not a real one. It says nothing about any real model.**")
    out += ["", f"{len(real)} run(s) counted. With this few runs per scenario one run moves a rate by "
                f"{round(100 / batch['repeats'])} percentage points; treat the rates as an indication, not a statistic.", ""]
    if skipped or errors:
        out += ["## Incomplete runs", ""]
        if skipped:
            out.append(f"- {len(skipped)} run(s) were skipped because the spend limit was reached ({batch['limits']}): "
                       + ", ".join(f"{r['scenario']}#{r['repeat']}" for r in skipped))
        out += [f"- {r['scenario']}#{r['repeat']}: {r['outcome']}: {r.get('error', '')}" for r in errors]
        out.append("")
    out += ["## Results per scenario", ""] + summary_table(batch["scenarios"], records)
    out += ["", "## Effort, cost and time", ""] + effort_table(batch["scenarios"], records)
    totals = [r["cost_usd"] for r in real]
    out += ["", f"Total: {len(real)} runs, {sum(r['tokens_in'] for r in real)} tokens in, "
                f"{sum(r['tokens_out'] for r in real)} out, list-price cost {money(totals, 'sum')}, "
                f"{sum(r['wall_seconds'] for r in real):.0f} s of run time. "
                "(Cost is tokens times the provider's list price from LiteLLM's table; a free tier charges nothing.)"]
    out += ["", "## Detector firings (count over all runs of the scenario)", ""] + detector_table(batch["scenarios"], records)
    out += ["", "## Audit enforced vs advisory", ""] + mode_comparison(records)
    out += ["", "## Every run", ""] + run_list(records)
    out.append("")
    return "\n".join(out)
