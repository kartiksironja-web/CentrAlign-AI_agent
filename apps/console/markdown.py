"""A very small Markdown to HTML converter, enough for the generated results files (no extra dependency).

Purpose: show evals/RESULTS*.md and similar files on a web page: headings, tables, lists, block quotes, code, bold and inline code.
Why this design: those files are generated by code with a fixed, simple shape, so a 50-line converter is clearer than a library; all
text is HTML-escaped first, so nothing in a results file can inject markup.
How it can fail: anything fancier than the above (nested lists, images, links) is shown as plain text, not rendered.
"""
import html
import re


def _inline(text: str) -> str:
    text = html.escape(text)
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
    return re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", text)


def _row(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def to_html(markdown: str) -> str:
    out, lines, i = [], markdown.splitlines(), 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("```"):
            j = i + 1
            while j < len(lines) and not lines[j].startswith("```"):
                j += 1
            out.append("<pre>" + html.escape("\n".join(lines[i + 1:j])) + "</pre>")
            i = j + 1
        elif line.startswith("|") and i + 1 < len(lines) and re.match(r"^\|[\s:|-]+\|?$", lines[i + 1]):
            head, i = _row(line), i + 2
            body = []
            while i < len(lines) and lines[i].startswith("|"):
                body.append(_row(lines[i]))
                i += 1
            out.append("<div class='scroll'><table><thead><tr>" + "".join(f"<th>{_inline(c)}</th>" for c in head) + "</tr></thead><tbody>"
                       + "".join("<tr>" + "".join(f"<td>{_inline(c)}</td>" for c in r) + "</tr>" for r in body) + "</tbody></table></div>")
        elif re.match(r"^#{1,4} ", line):
            level = len(line) - len(line.lstrip("#"))
            out.append(f"<h{level + 1}>{_inline(line[level + 1:])}</h{level + 1}>")
            i += 1
        elif line.startswith("- "):
            items = []
            while i < len(lines) and lines[i].startswith("- "):
                items.append(f"<li>{_inline(lines[i][2:])}</li>")
                i += 1
            out.append("<ul>" + "".join(items) + "</ul>")
        elif line.startswith(">"):
            out.append(f"<blockquote>{_inline(line.lstrip('> '))}</blockquote>")
            i += 1
        elif line.strip():
            out.append(f"<p>{_inline(line)}</p>")
            i += 1
        else:
            i += 1
    return "\n".join(out)
